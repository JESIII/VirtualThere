using System.Net;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using System.Text;

namespace Vht.Transport.Tls;

/// <summary>
/// Generates and loads the server's self-signed certificate, and computes the SPKI pin clients use
/// instead of a CA chain (ARCHITECTURE.md §6.1, §6.5, §7).
/// </summary>
/// <remarks>
/// <para>
/// One ECDSA P-256 key, generated on first run, valid for ten years, with <c>serverAuth</c> EKU and a
/// SAN covering the configured server name, <c>localhost</c> and the loopback addresses. There is no
/// CA, no CSR and no client-certificate ceremony in v1: trust is the pinned public key, and the pin is
/// additionally published in the DNS-SD TXT record so discovery can pre-confirm it.
/// </para>
/// <para>
/// The key is written as an unencrypted PKCS#8 PEM because there is no second secret to protect it
/// with — the file's ACL <em>is</em> the protection. <see cref="SecureFileStore"/> refuses to leave it
/// readable by other accounts.
/// </para>
/// </remarks>
public static class ServerCertificateManager
{
    private const string CertificateFileName = "server.crt.pem";
    private const string PrivateKeyFileName = "server.key.pem";

    /// <summary>Loads the certificate from <paramref name="directory"/>, generating one on first run.</summary>
    /// <param name="directory">Directory holding the certificate pair. Created if absent.</param>
    /// <param name="serverName">DNS name to place in the SAN.</param>
    /// <param name="allowInsecureKeyStorage">Forwarded to <see cref="SecureFileStore"/>.</param>
    /// <param name="created">True when a new key was generated by this call.</param>
    public static X509Certificate2 LoadOrCreate(
        string directory,
        string serverName,
        out bool created,
        bool allowInsecureKeyStorage = false)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(directory);
        ArgumentException.ThrowIfNullOrWhiteSpace(serverName);

        var certificatePath = Path.Combine(directory, CertificateFileName);
        var keyPath = Path.Combine(directory, PrivateKeyFileName);

        if (File.Exists(certificatePath) && File.Exists(keyPath))
        {
            created = false;
            var loaded = X509Certificate2.CreateFromPemFile(certificatePath, keyPath);
            return MakeSchannelFriendly(loaded);
        }

        Directory.CreateDirectory(directory);
        SecureFileStore.HardenDirectory(directory, allowInsecureKeyStorage);

        using var key = ECDsa.Create(ECCurve.NamedCurves.nistP256);
        var subject = new X500DistinguishedName($"CN={EscapeRdn(serverName)}, O=VirtualThere");
        var request = new CertificateRequest(subject, key, HashAlgorithmName.SHA256);
        request.CertificateExtensions.Add(new X509BasicConstraintsExtension(false, false, 0, critical: true));
        request.CertificateExtensions.Add(new X509KeyUsageExtension(
            X509KeyUsageFlags.DigitalSignature | X509KeyUsageFlags.KeyEncipherment,
            critical: true));
        request.CertificateExtensions.Add(new X509EnhancedKeyUsageExtension(
            new OidCollection { new("1.3.6.1.5.5.7.3.1") },
            critical: true));

        var san = new SubjectAlternativeNameBuilder();
        san.AddDnsName(serverName);
        san.AddDnsName("localhost");
        san.AddIpAddress(IPAddress.Loopback);
        san.AddIpAddress(IPAddress.IPv6Loopback);
        request.CertificateExtensions.Add(san.Build());
        request.CertificateExtensions.Add(new X509SubjectKeyIdentifierExtension(request.PublicKey, false));

        var now = DateTimeOffset.UtcNow;
        using var generated = request.CreateSelfSigned(now.AddMinutes(-5), now.AddYears(10));

        SecureFileStore.WriteSecretFile(
            certificatePath,
            Encoding.ASCII.GetBytes(generated.ExportCertificatePem()),
            allowInsecureKeyStorage);
        SecureFileStore.WriteSecretFile(
            keyPath,
            Encoding.ASCII.GetBytes(key.ExportPkcs8PrivateKeyPem()),
            allowInsecureKeyStorage);

        created = true;
        var fresh = X509Certificate2.CreateFromPemFile(certificatePath, keyPath);
        return MakeSchannelFriendly(fresh);
    }

    /// <summary>
    /// Re-imports an ephemeral PEM-loaded certificate through PKCS#12 so the private key has a stable
    /// key handle, which Schannel requires for <c>SslStream.AuthenticateAsServerAsync</c>.
    /// </summary>
    private static X509Certificate2 MakeSchannelFriendly(X509Certificate2 certificate)
    {
        byte[] pkcs12;
        try
        {
            pkcs12 = certificate.Export(X509ContentType.Pkcs12);
        }
        catch (CryptographicException)
        {
            // No exportable private key: PEM load already produced a usable handle.
            return certificate;
        }

        try
        {
            var reimported = X509CertificateLoader.LoadPkcs12(pkcs12, null, X509KeyStorageFlags.DefaultKeySet);
            certificate.Dispose();
            return reimported;
        }
        catch (CryptographicException)
        {
            return certificate;
        }
        finally
        {
            CryptographicOperations.ZeroMemory(pkcs12);
        }
    }

    /// <summary>SPKI SHA-256 pin of a certificate, base64url without padding — the value published in DNS-SD.</summary>
    public static string ComputeSpkiPin(X509Certificate2 certificate)
    {
        ArgumentNullException.ThrowIfNull(certificate);
        return ComputeSpkiPin(certificate.PublicKey.ExportSubjectPublicKeyInfo());
    }

    /// <summary>SPKI SHA-256 pin of raw SubjectPublicKeyInfo bytes, base64url without padding.</summary>
    public static string ComputeSpkiPin(ReadOnlySpan<byte> subjectPublicKeyInfo) =>
        Base64Url(SHA256.HashData(subjectPublicKeyInfo));

    /// <summary>base64url without padding (RFC 4648 §5), as used by the DNS-SD TXT record.</summary>
    public static string Base64Url(ReadOnlySpan<byte> bytes) =>
        Convert.ToBase64String(bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_');

    /// <summary>Number of decimal digits a pin has, for docs and tests.</summary>
    public static int PinLength => 43; // base64url of 32 bytes, unpadded

    private static string EscapeRdn(string value) => value.Replace(",", "\\,", StringComparison.Ordinal)
        .Replace("+", "\\+", StringComparison.Ordinal)
        .Replace("\"", "\\\"", StringComparison.Ordinal)
        .Replace("\\", "\\\\", StringComparison.Ordinal);
}
